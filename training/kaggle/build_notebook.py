"""Build the Kaggle notebook that trains Kalaris STT v0.

The notebook carries copies of this repo's own code, so it needs no access to the
private GitHub repo. Rebuild it after changing any file in FILES:

    .venv/bin/python training/kaggle/build_notebook.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "training" / "kaggle" / "kalaris_v0.ipynb"

FILES = [
    "stt_eval/__init__.py",
    "stt_eval/manifest.py",
    "stt_eval/hf_audio.py",
    "stt_eval/normalize.py",
    "stt_eval/score.py",
    "stt_eval/bench.py",
    "stt_eval/leakage.py",
    "stt_eval/cli.py",
    "stt_eval/backends/__init__.py",
    "stt_eval/backends/base.py",
    "stt_eval/backends/nemo_backend.py",
    "training/prepare_data.py",
    "training/train_tokenizer.py",
    "training/finetune.py",
    "configs/datasets.yaml",
    "configs/benchmarks.yaml",
    "training/configs/v0.yaml",
]


def markdown(text: str) -> dict:
    return {"cell_type": "markdown", "metadata": {}, "source": text.strip().splitlines(keepends=True)}


def code(text: str) -> dict:
    return {"cell_type": "code", "metadata": {}, "execution_count": None, "outputs": [], "source": text.strip().splitlines(keepends=True)}


INTRO = """
# Kalaris STT v0: train on a free Kaggle GPU

Fine-tunes NVIDIA Parakeet TDT 0.6B v3 for Hindi, Hinglish and English, using open data the owner approved on 2026-11-08: MUCS 2021 Hinglish, FLEURS Hindi and LibriSpeech.

**Before running:** in the right-hand panel, set **Accelerator** to a GPU (T4 or P100) and turn **Internet** on. Internet needs a phone-verified Kaggle account. Then choose **Save Version → Save & Run All**, so the run continues after you close the tab.

**Time:** Kaggle stops a session at 12 hours. The notebook budgets about 11 and stops cleanly. To continue in a new session, add this notebook's output as an input and set `RESUME` in the settings cell.

**Outputs** (in `/kaggle/working/v0`): `head.nemo`, `full.nemo`, the tokenizer, `dev_scores.json`, and `checkpoints_full/last.ckpt` for resuming.

Generated by `training/kaggle/build_notebook.py`. Edit the repo files, not this notebook.
"""

SETTINGS = """
import os, time, json, shutil, subprocess, sys
from pathlib import Path

START = time.time()
BUDGET_HOURS = 11.0          # Kaggle stops at 12; this leaves time to save
RESUME = None                # e.g. "/kaggle/input/<previous-output>/v0/checkpoints_full/last.ckpt"
SKIP_HEAD = False            # True when resuming a full stage from a saved head.nemo
HEAD_FROM = None             # e.g. "/kaggle/input/<previous-output>/v0/head.nemo"

REPO = Path("/kaggle/working/kalaris-stt")
DATA = Path("/kaggle/temp") if Path("/kaggle/temp").exists() else Path("/tmp/kalaris")
DATA.mkdir(parents=True, exist_ok=True)

def hours_left():
    return BUDGET_HOURS - (time.time() - START) / 3600

def sh(command):
    print("$", command, flush=True)
    subprocess.run(command, shell=True, check=True, cwd=REPO)

print(subprocess.run("nvidia-smi --query-gpu=name,memory.total --format=csv", shell=True, capture_output=True, text=True).stdout)
print(subprocess.run(f"df -h {DATA} /kaggle/working", shell=True, capture_output=True, text=True).stdout)
"""

INSTALL = """
!pip install -q "nemo_toolkit[asr]==3.0.0" "whisper-normalizer>=0.1" pyarrow soundfile pyyaml huggingface_hub
import nemo, torch
print("NeMo", nemo.__version__, "| torch", torch.__version__, "| CUDA", torch.cuda.is_available())
assert torch.cuda.is_available(), "No GPU: set Accelerator to a GPU in the right-hand panel."
"""

PATHS = """
# Point the config at this machine's folders.
import yaml
config = yaml.safe_load((REPO / "training/configs/v0.yaml").read_text())
config["tokenizer_dir"] = str(DATA / "tokenizers/v0")
config["train_manifest"] = str(DATA / "training/v0/train.json")
config["dev_manifest"] = str(DATA / "training/v0/dev.json")
config["output_dir"] = "/kaggle/working/v0"
if HEAD_FROM:
    config["init_from"] = HEAD_FROM
(REPO / "training/configs/v0_kaggle.yaml").write_text(yaml.safe_dump(config, allow_unicode=True))
os.environ["PYTHONPATH"] = str(REPO)
os.environ["PYTHONWARNINGS"] = "ignore"
"""

PREPARE = """
# Download and filter the approved data. MUCS is about 9 GB, so this takes a while.
sh(f"python training/prepare_data.py training/configs/v0_kaggle.yaml --output-root {DATA / 'training'}")
print((DATA / "training/v0/report.txt").read_text())
"""

TOKENIZER = """
# One tokenizer for Devanagari, Latin and later-wave scripts.
sh(f"python training/train_tokenizer.py --manifest {DATA / 'training/v0/train.json'} "
   f"--output {DATA / 'tokenizers/v0'} --vocab-size 2048 "
   "--extra-fleurs bn_in,mr_in,te_in,ta_in,gu_in,kn_in,ml_in,pa_in,or_in")
"""

HEAD = """
# Stage 1: new tokenizer, decoder and joint; encoder frozen.
if not SKIP_HEAD:
    head_seconds = int(min(2.0, hours_left() / 4) * 3600)
    sh(f"python training/finetune.py training/configs/v0_kaggle.yaml --stage head --max-seconds {head_seconds}")
"""

FULL = """
# Stage 2: everything trains. Stops cleanly before Kaggle's limit and saves full.nemo.
full_seconds = int((hours_left() - 0.75) * 3600)
assert full_seconds > 1800, "Too little time left. Resume in a new session."
resume = f" --resume {RESUME}" if RESUME else ""
sh(f"python training/finetune.py training/configs/v0_kaggle.yaml --stage full --max-seconds {full_seconds}{resume}")
"""

SCORE = """
# Dev scores only (no benchmark sets). Hindi, Hinglish and English are scored separately.
scores = {}
for language, scored_as in [("hi", "hi"), ("hinglish", "hinglish"), ("en", "en")]:
    manifest = DATA / f"training/v0/dev_{language}.json"
    if not manifest.exists():
        continue
    out = Path(f"/kaggle/working/v0/dev_{language}.jsonl")
    sh(f"python -m stt_eval.cli transcribe --backend nemo --model /kaggle/working/v0/full.nemo "
       f"--manifest {manifest} --out {out} --language {scored_as}")
    result = subprocess.run(
        [sys.executable, "-m", "stt_eval.cli", "score", "--manifest", str(manifest), "--hypotheses", str(out), "--language", scored_as],
        cwd=REPO, capture_output=True, text=True, check=True)
    scores[language] = json.loads(result.stdout)
    print(language, round(scores[language]["wer"]["rate"], 2), "WER on", scores[language]["clips"], "dev clips")
Path("/kaggle/working/v0/dev_scores.json").write_text(json.dumps(scores, indent=2, ensure_ascii=False))
"""

SAVE = """
# Keep the tokenizer and data report with the model, and drop older checkpoints to stay under 20 GB.
shutil.copytree(DATA / "tokenizers/v0", "/kaggle/working/v0/tokenizer", dirs_exist_ok=True)
shutil.copy(DATA / "training/v0/report.txt", "/kaggle/working/v0/data_report.txt")
for stage in ("head", "full"):
    folder = Path(f"/kaggle/working/v0/checkpoints_{stage}")
    for checkpoint in folder.glob("*.ckpt") if folder.exists() else []:
        if checkpoint.name != "last.ckpt":
            checkpoint.unlink()
print(subprocess.run("du -sh /kaggle/working/v0/*", shell=True, capture_output=True, text=True).stdout)
"""


def main() -> None:
    cells = [markdown(INTRO), code(SETTINGS), code(INSTALL), markdown("## Code from the kalaris-stt repo")]
    for relative in FILES:
        text = (ROOT / relative).read_text(encoding="utf-8")
        cells.append(code(f"%%writefile {'/kaggle/working/kalaris-stt/' + relative}\n{text}"))
    cells[4:4] = [code("!mkdir -p " + " ".join(sorted({f"/kaggle/working/kalaris-stt/{Path(f).parent}" for f in FILES})))]
    cells += [
        markdown("## Train"), code(PATHS), code(PREPARE), code(TOKENIZER), code(HEAD), code(FULL),
        markdown("## Dev scores and outputs"), code(SCORE), code(SAVE),
    ]
    notebook = {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python"},
            "kaggle": {"accelerator": "gpu", "isInternetEnabled": True},
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }
    OUTPUT.write_text(json.dumps(notebook, indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"{len(cells)} cells -> {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
